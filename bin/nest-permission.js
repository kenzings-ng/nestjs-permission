#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const readline = require('readline');

const args = process.argv.slice(2);
const command = args[0];
const dryRun = args.includes('--dry-run');
const databaseArgument = readArgument('--database');

if (command !== 'init') {
  console.log('Usage: nest-permission init [--database mongoose|prisma|typeorm] [--dry-run]');
  process.exit(command ? 1 : 0);
}

main().catch((error) => {
  console.error(`nest-permission: ${error.message}`);
  process.exit(1);
});

async function main() {
  const cwd = process.cwd();
  const packagePath = path.join(cwd, 'package.json');
  if (!fs.existsSync(packagePath)) throw new Error('No package.json found in the current directory.');

  const packageJson = JSON.parse(fs.readFileSync(packagePath, 'utf8'));
  const database = databaseArgument || await chooseDatabase(detectDatabases(packageJson));
  if (!['mongoose', 'prisma', 'typeorm'].includes(database)) {
    throw new Error(`Unsupported database adapter '${database}'.`);
  }

  const targetDirectory = path.join(cwd, 'src', 'permissions');
  const target = path.join(targetDirectory, database === 'mongoose'
    ? 'permission.module.ts'
    : 'permission.repository.ts');
  const source = database === 'mongoose' ? mongooseModuleSource() : repositorySkeletonSource(database);

  if (fs.existsSync(target)) {
    throw new Error(`${path.relative(cwd, target)} already exists; refusing to overwrite it.`);
  }

  if (dryRun) {
    console.log(`[dry-run] Would create ${path.relative(cwd, target)} for ${database}.`);
    return;
  }

  fs.mkdirSync(targetDirectory, { recursive: true });
  fs.writeFileSync(target, source, 'utf8');
  console.log(`Created ${path.relative(cwd, target)}.`);
  console.log(nextStep(database));
}

function readArgument(name) {
  const index = args.indexOf(name);
  return index === -1 ? undefined : args[index + 1];
}

function detectDatabases(packageJson) {
  const dependencies = {
    ...(packageJson.dependencies || {}),
    ...(packageJson.devDependencies || {}),
  };
  const found = [];
  if (dependencies.mongoose || dependencies['@nestjs/mongoose']) found.push('mongoose');
  if (dependencies.prisma || dependencies['@prisma/client']) found.push('prisma');
  if (dependencies.typeorm || dependencies['@nestjs/typeorm']) found.push('typeorm');
  return found;
}

async function chooseDatabase(detected) {
  if (detected.length === 1) {
    console.log(`Detected ${detected[0]}.`);
    return detected[0];
  }
  const choices = detected.length ? detected : ['mongoose', 'prisma', 'typeorm'];
  console.log(`Select your database adapter:\n${choices.map((item, index) => `${index + 1}. ${item}`).join('\n')}`);
  const answer = await ask('Choice: ');
  const selected = choices[Number(answer) - 1];
  if (!selected) throw new Error('Invalid adapter selection.');
  return selected;
}

function ask(question) {
  const input = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) => input.question(question, (answer) => {
    input.close();
    resolve(answer.trim());
  }));
}

function mongooseModuleSource() {
  return `import { Module } from '@nestjs/common';
import { MongoosePermissionModule } from '@kenzings/nest-permission/mongoose';

@Module({
  imports: [MongoosePermissionModule.forRoot()],
})
export class PermissionModule {}
`;
}

function repositorySkeletonSource(database) {
  return `import { Injectable } from '@nestjs/common';
import {
  Permission,
  PermissionRepository,
  PermissionSubjectId,
} from '@kenzings/nest-permission';

/** ${database} adapter skeleton generated by nest-permission. */
@Injectable()
export class ${capitalize(database)}PermissionRepository implements PermissionRepository {
  async createPermission(name: Permission, guardName: string): Promise<void> { throw new Error('Implement createPermission'); }
  async deletePermission(name: Permission, guardName: string): Promise<void> { throw new Error('Implement deletePermission'); }
  async createRole(name: string, guardName: string): Promise<void> { throw new Error('Implement createRole'); }
  async deleteRole(name: string, guardName: string): Promise<void> { throw new Error('Implement deleteRole'); }
  async permissionExists(name: Permission, guardName: string): Promise<boolean> { throw new Error('Implement permissionExists'); }
  async roleExists(name: string, guardName: string): Promise<boolean> { throw new Error('Implement roleExists'); }
  async setRolePermissions(role: string, permissions: Permission[], guardName: string): Promise<void> { throw new Error('Implement setRolePermissions'); }
  async getRolePermissions(role: string, guardName: string): Promise<Permission[]> { throw new Error('Implement getRolePermissions'); }
  async setUserRoles(userId: PermissionSubjectId, roles: string[], guardName: string): Promise<void> { throw new Error('Implement setUserRoles'); }
  async getUserRoles(userId: PermissionSubjectId, guardName: string): Promise<string[]> { throw new Error('Implement getUserRoles'); }
  async setUserPermissions(userId: PermissionSubjectId, permissions: Permission[], guardName: string): Promise<void> { throw new Error('Implement setUserPermissions'); }
  async getUserPermissions(userId: PermissionSubjectId, guardName: string): Promise<Permission[]> { throw new Error('Implement getUserPermissions'); }
}
`;
}

function capitalize(value) {
  return value.slice(0, 1).toUpperCase() + value.slice(1);
}

function nextStep(database) {
  if (database === 'mongoose') {
    return 'Import PermissionModule into AppModule. Mongoose will create the indexed collections on connection.';
  }
  return 'Implement the generated repository, then register it with NestPermissionModule.forRootWithRepository(...).';
}
